"""Собрать короткую инструкцию по демонстрационному стенду в .docx.

    python -m tools.make_demo_guide

Снимки экрана лежат в docs/screens и сняты с работающего стенда: цифры на них
проставлены поверх интерфейса, поэтому подписи в тексте и кружки на картинке
всегда об одном и том же. Пересняты — перезапустите сборку, текст менять
не придётся.
"""

from __future__ import annotations

import os

from docx import Document
from docx.enum.text import WD_ALIGN_PARAGRAPH
from docx.shared import Inches, Pt, RGBColor

from libs.config import project_root

STAND_URL = os.environ.get("STAND_URL", "http://127.0.0.1:8097/")
SCREENS = project_root() / "docs" / "screens"


def picture(doc: Document, name: str, caption: str, width_in: float = 6.6) -> None:
    """Снимок экрана с подписью под ним."""
    doc.add_picture(str(SCREENS / name), width=Inches(width_in))
    doc.paragraphs[-1].alignment = WD_ALIGN_PARAGRAPH.CENTER

    para = doc.add_paragraph()
    para.alignment = WD_ALIGN_PARAGRAPH.CENTER
    run = para.add_run(caption)
    run.italic = True
    run.font.size = Pt(9)
    run.font.color.rgb = RGBColor(0x60, 0x60, 0x60)


def legend(doc: Document, items: list[str]) -> None:
    """Расшифровка цифр на снимке."""
    for index, text in enumerate(items, start=1):
        # Не список: маркер рядом с номером спорил бы с цифрой на снимке.
        para = doc.add_paragraph()
        para.paragraph_format.left_indent = Inches(0.25)
        para.paragraph_format.space_after = Pt(3)
        number = para.add_run(f"{index} — ")
        number.bold = True
        para.add_run(text)


def main() -> None:
    doc = Document()
    normal = doc.styles["Normal"]
    normal.font.name = "Calibri"
    normal.font.size = Pt(11)

    # Поля уже обычных: снимки экрана широкие, и чем больше они на странице,
    # тем меньше придётся вглядываться.
    for section in doc.sections:
        section.left_margin = section.right_margin = Inches(0.8)
        section.top_margin = section.bottom_margin = Inches(0.7)

    doc.add_heading("Демонстрационный стенд ИИ-ассистента: как смотреть", level=0)

    doc.add_paragraph(
        "Стенд показывает работу сценарного модуля: как система в реальном времени "
        "разбирает поток распознавания, голосом ведёт сотрудника по регламенту, "
        "фиксирует нарушения с указанием последствий и формирует отчёт о занятии."
    )

    # ------------------------------------------------------------------
    doc.add_heading("Как открыть", level=1)
    para = doc.add_paragraph()
    para.add_run("Адрес: ").bold = True
    para.add_run(STAND_URL)
    doc.add_paragraph(
        "Браузер — Chrome или Edge, звук включить: половина происходящего — это голос "
        "ассистента. После перезапуска стенду нужно около полминуты на подготовку речи.",
        style="List Bullet",
    )
    doc.add_paragraph(
        "Смотреть можно всем сразу: у каждого своё занятие со своим сюжетом, журналом "
        "и голосом. Чужие действия на ваш экран не влияют, и наоборот. Несколько "
        "вкладок у одного человека — это одно занятие: в них видно одно и то же.",
        style="List Bullet",
    )

    # ------------------------------------------------------------------
    doc.add_heading("Что на экране", level=1)
    picture(doc, "01-obzor.png", "Экран сразу после открытия: сюжет — проверка средств защиты")
    legend(doc, [
        "Выбор сюжета. Их два: проверка средств защиты и верхний налив ЛВЖ.",
        "Ситуация для показа. Нажатие на неё начинает занятие — отдельная кнопка "
        "запуска на этом сюжете не нужна.",
        "Окно разбора потока. Там, где есть съёмка, идёт видео с разметкой "
        "распознавания; где съёмки нет — лента наблюдений.",
        "Журнал занятия: команды ассистента, зачёты шагов, предупреждения.",
        "Последовательность шагов регламента с отметками выполнения.",
        "Отчёт по завершённому занятию — файл Word.",
        "Реплика обучаемого: доклад о готовности, «повтори», «помощь».",
    ])

    # ------------------------------------------------------------------
    doc.add_heading("Сюжет 1. Проверка средств защиты (на реальной съёмке)", level=1)
    doc.add_paragraph(
        "Выберите в списке сверху сюжет «СИЗ-01» и нажмите «Сотрудник надевает каску»."
    )
    doc.add_paragraph("Что произойдёт:")
    for text in (
        "Ассистент объявляет проверку и просит направить камеру на себя.",
        "В кадре сотрудник с каской в руке. Система фиксирует, что каска не надета, "
        "и выдерживает отведённое на шаг время.",
        "Время истекает — объявляется нарушение и его последствия: работа без каски "
        "запрещена, это риск тяжёлой травмы головы.",
        "Сотрудник надевает каску, система засчитывает проверку и допускает к работе.",
        "Нажмите «Доклад о готовности» — ассистент принимает доклад, занятие завершено.",
    ):
        doc.add_paragraph(text, style="List Number")

    picture(
        doc, "02-narushenie.png",
        "Каска в руке: время вышло, объявлено нарушение и его последствия. Кадр замер",
    )
    doc.add_paragraph(
        "Кадр в этот момент действительно замирает, и это не монтаж: пока система "
        "выдерживает время, она продолжает получать настоящие наблюдения «каска "
        "не надета» и приходит к выводу сама. Съёмка идёт дальше только после того, "
        "как ассистент договорит предупреждение."
    )
    picture(
        doc, "03-kaska-nadeta.png",
        "Каска надета: шаг зачтён, допуск разрешён, система ждёт доклада о готовности",
    )

    # ------------------------------------------------------------------
    doc.add_heading("Сюжет 2. Верхний налив ЛВЖ (семь шагов регламента)", level=1)
    doc.add_paragraph(
        "Выберите сюжет «КФТ-01». Съёмки по этой операции пока нет, поэтому поток "
        "распознавания имитируется — видно его разбор в том же окне слева. "
        "Выберите ситуацию из списка справа внизу: занятие начнётся вместе с ней."
    )
    picture(doc, "04-naliv.png", "Верхний налив: разбор потока слева, ход занятия справа")
    legend(doc, [
        "Лента разбора: время, что распознано и с какой уверенностью. Отдельной "
        "строкой с полосой слева — момент, когда состояние сменилось.",
        "Ситуации для показа — от чистого прогона до нарушения порядка и обрыва связи.",
        "Пульт: ручное управление состояниями.",
    ])

    doc.add_paragraph("Ситуации, которые стоит показать:")
    for text in (
        "«Чистый прогон» — все семь шагов в правильном порядке.",
        "«Люк без заземления» — нарушение порядка: система останавливает работу "
        "и объясняет, чем это грозит, а затем принимает исправление.",
        "«Обрыв видеопотока» — отказ камеры. Система сообщает о технической проблеме "
        "и приостанавливает оценку, а не записывает её в ошибку сотрудника.",
        "«Дребезг трубы» — неустойчивое распознавание на границе состояний: "
        "проверка на то, что система не дёргается и не выдаёт лишних оценок.",
    ):
        doc.add_paragraph(text, style="List Bullet")

    picture(
        doc, "05-pult.png",
        "Пульт: любую обстановку можно задать вручную и посмотреть, как система отзовётся",
        width_in=3.6,
    )
    doc.add_paragraph(
        "Для показа с пульта занятие начинают кнопкой «Старт»."
    )

    # ------------------------------------------------------------------
    doc.add_heading("Отчёт", level=1)
    doc.add_paragraph(
        "Кнопка «Отчёт» собирает документ Word по завершённому занятию: сводка, разбор "
        "и журнал действий с отметками времени."
    )

    doc.add_heading("На что обратить внимание", level=1)
    for text in (
        "Ассистент не просто фиксирует нарушение, а называет последствие — "
        "это требование к обучению, а не украшение.",
        "Система различает «нарушение» и «не вижу»: при плохом кадре или обрыве связи "
        "она говорит об этом прямо и не приписывает сотруднику ошибку.",
        "Порядок шагов контролируется: действие вне очереди останавливает работу.",
        "Регламент задаётся описанием, а не программируется: добавление шага или "
        "нового элемента защиты не требует переписывания системы.",
    ):
        doc.add_paragraph(text, style="List Bullet")

    out = project_root() / "Демонстрационный стенд — как смотреть.docx"
    doc.save(str(out))
    print("готово:", out.name)


if __name__ == "__main__":
    main()
